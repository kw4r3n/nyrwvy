//! Public emitCSharp orchestration; generated artifacts retain the viewer writer's confinement.
const std = @import("std");
const q = @import("query.zig");
const recipe = @import("recipe.zig");
const emitter = @import("csharp_emitter");
const host = @import("root");
const files = @import("view_file.zig");
const facade = @import("csharp_facade.zig");
const V = std.json.Value;
const marker = "// Generated by Nyrwvy.";
fn string(d: *recipe.Decoder, v: V, key: []const u8) ![]const u8 {
    return d.requiredString(v, key);
}
fn profile(d: *recipe.Decoder, v: V) !V {
    const r = d.r;
    const a = r.a;
    const k = try string(d, v, "kind");
    var bindings: std.ArrayList(V) = .empty;
    var concurrent: std.ArrayList(V) = .empty;
    if (emitter.eq(k, "empty")) try d.ensureFields("/profile", v, "empty C# profile", &.{"kind"}, &.{"kind"}) else if (emitter.eq(k, "systemConsoleWriteLine")) {
        try d.ensureFields("/profile", v, "System.Console.WriteLine C# profile", &.{ "kind", "operationId" }, &.{ "kind", "operationId" });
        const id = try d.stableId("operationId", try string(d, v, "operationId"));
        try bindings.append(a, try emitter.object(a, &.{ "operationId", "kind" }, &.{ emitter.string(id), emitter.string("systemConsoleWriteLine") }));
    } else if (emitter.eq(k, "externalImplementations")) {
        try d.ensureFields("/profile", v, "External C# implementations profile", &.{ "kind", "operationIds", "concurrentCapabilityIds", "tables" }, &.{ "kind", "operationIds" });
        for (try d.array(v, "operationIds")) |id| {
            if (id != .string) return r.fail("External operation ID must be a string.", .{});
            try bindings.append(a, try emitter.object(a, &.{ "operationId", "kind" }, &.{ emitter.string(try d.stableId("operationId", try q.readable(r, id.string))), emitter.string("externalImplementation") }));
        }
        if (v.object.contains("concurrentCapabilityIds")) for (try d.array(v, "concurrentCapabilityIds")) |id| {
            if (id != .string) return r.fail("Concurrent capability ID must be a string.", .{});
            try concurrent.append(a, emitter.string(try d.stableId("capabilityId", try q.readable(r, id.string))));
        };
        var paths: std.ArrayList([]const u8) = .empty;
        if (v.object.contains("tables")) for (try d.array(v, "tables")) |path| {
            if (path != .string) return r.fail("A mapping table must be a file path.", .{});
            const text = try q.readable(r, path.string);
            if (q.isBlank(try std.unicode.utf8ToUtf16LeAlloc(a, text))) return r.fail("A mapping table must be a file path.", .{});
            try paths.append(a, text);
        };
        try bindings.appendSlice(a, try @import("csharp_mapping.zig").bindings(r, paths.items));
    } else return r.fail("Unsupported C# profile '{s}'.", .{k});
    return emitter.object(a, &.{ "capabilityBindings", "concurrentCapabilityIds" }, &.{ try emitter.array(a, bindings.items), try emitter.array(a, concurrent.items) });
}
fn pathOutcome(r: *q.Request, outcome: files.Outcome) ![]const u8 {
    return switch (outcome) {
        .written => |path| path,
        .refused => |message| {
            r.rejection = .{ .code = "EmitWriteFailed", .message = message };
            return error.Rejected;
        },
        .internal => {
            r.rejection = .{ .code = "InternalError", .message = "Unexpected internal failure; this request was not applied and the session is unchanged." };
            return error.Rejected;
        },
    };
}
fn differentFiles(r: *q.Request, first: []const u8, second: []const u8) !void {
    const os = @import("builtin").os.tag;
    const same_name = if (os == .windows or os == .macos) std.ascii.eqlIgnoreCase(first, second) else emitter.eq(first, second);
    const aliases = same_name or (files.sameFile(first, second) catch |err| {
        r.rejection = .{ .code = "EmitWriteFailed", .message = try std.fmt.allocPrint(r.a, "Could not verify distinct output files: {s}.", .{@errorName(err)}) };
        return error.Rejected;
    });
    if (aliases) {
        r.rejection = .{ .code = "EmitWriteFailed", .message = try std.fmt.allocPrint(r.a, "output and facade must name different files; both resolve to {s}.", .{first}) };
        return error.Rejected;
    }
}
fn facadeFailure(r: *q.Request, problems: []const facade.Problem) !void {
    var body: std.Io.Writer.Allocating = .init(r.a);
    const w = &body.writer;
    try w.writeAll(",\"problems\":[");
    for (problems, 0..) |p, i| {
        if (i > 0) try w.writeByte(',');
        try w.writeAll("{\"code\":");
        try host.writeString(w, p.code);
        try w.writeAll(",\"name\":");
        try host.writeString(w, p.name);
        try w.writeAll(",\"declarations\":[");
        for (p.declarations, 0..) |d, j| {
            if (j > 0) try w.writeByte(',');
            try w.writeAll("{\"kind\":");
            try host.writeString(w, d.kind);
            try w.writeAll(",\"id\":");
            try host.writeString(w, d.id);
            try w.writeByte('}');
        }
        try w.writeAll("]}");
    }
    try w.writeByte(']');
    r.rejection = .{ .code = problems[0].code, .message = try std.fmt.allocPrint(r.a, "The facade cannot name '{s}': {d} display name problem(s) among the exported declarations and the types they reach.", .{ problems[0].name, problems.len }), .fields = body.written() };
    return error.Rejected;
}
pub fn run(r: *q.Request, out: *std.Io.Writer) !void {
    var d: recipe.Decoder = .{ .r = r, .duplicates = try recipe.duplicatePaths(r.a, r.line) };
    const request: V = .{ .object = r.root };
    try d.ensureFields("", request, "emitCSharp request", &.{ "id", "op", "profile", "output", "facade" }, &.{ "id", "op", "profile" });
    const output = if (r.root.contains("output")) try string(&d, request, "output") else null;
    const facade_path = if (r.root.contains("facade")) try string(&d, request, "facade") else null;
    const resolved_profile = try profile(&d, try d.property(request, "profile"));
    try r.ensureUsable();
    if (try host.verifyPersisted(r.a)) |rejection| {
        r.rejection = rejection;
        return error.Rejected;
    }
    const ir = try @import("run_pure.zig").lowered(r, null);
    const artifact = switch (try emitter.emit(r.a, ir, resolved_profile)) {
        .artifact => |artifact| artifact,
        .failure => |failure| {
            r.rejection = .{ .code = failure.code, .message = failure.message };
            if (failure.details != .null) r.rejection.details = try std.json.Stringify.valueAlloc(r.a, failure.details, .{});
            return error.Rejected;
        },
    };
    var facade_source: ?[]const u8 = null;
    if (facade_path != null) {
        var host_ids: std.ArrayList([]const u8) = .empty;
        var table_opids: std.ArrayList([]const u8) = .empty;
        var table_capids: std.ArrayList([]const u8) = .empty;
        for (emitter.arr(resolved_profile, "capabilityBindings")) |binding| {
            if (emitter.eq(emitter.kind(binding), "externalImplementation")) try host_ids.append(r.a, emitter.str(binding, "operationId"));
            if (emitter.eq(emitter.kind(binding), "native") and !emitter.get(emitter.get(binding, "native"), "handle").bool) try table_opids.append(r.a, emitter.str(binding, "operationId"));
        }
        for (try q.typedVisible(r, "capability")) |cap| {
            var is_table = false;
            for (cap.operations()) |op| {
                for (table_opids.items) |id| {
                    if (emitter.eq(id, q.idOf(op))) is_table = true;
                }
            }
            if (is_table) try table_capids.append(r.a, q.idOf(cap));
        }

        switch (try facade.generate(r, host_ids.items, table_capids.items)) {
            .source => |source| facade_source = source,
            .problems => |problems| return facadeFailure(r, problems),
        }
    }
    const output_check = if (output) |path| try files.check(r.a, r.snapshot_path, path, ".cs", "", marker) else null;
    if (output_check != null and output_check.? == .internal) _ = try pathOutcome(r, output_check.?);
    const facade_check = if (facade_path) |path| try files.check(r.a, r.snapshot_path, path, ".cs", "", marker) else null;
    if (facade_check != null and facade_check.? == .internal) _ = try pathOutcome(r, facade_check.?);
    const checked_output = if (output_check) |checked| try pathOutcome(r, checked) else null;
    const checked_facade = if (facade_check) |checked| try pathOutcome(r, checked) else null;
    if (checked_output != null and checked_facade != null) try differentFiles(r, checked_output.?, checked_facade.?);
    const written = if (output) |path| try pathOutcome(r, try files.write(r.a, r.snapshot_path, path, ".cs", "", marker, artifact.source)) else null;
    // A later facade failure must not read as if the output were untouched.
    errdefer if (written) |path| if (r.rejection.code.len > 0) {
        r.rejection.message = std.fmt.allocPrint(r.a, "{s} The implementation file {s} was already replaced.", .{ r.rejection.message, path }) catch r.rejection.message;
    };
    // Initially missing Unicode aliases become observable after publishing the implementation.
    if (written != null and checked_facade != null) try differentFiles(r, written.?, checked_facade.?);
    const facade_written = if (facade_path) |path| try pathOutcome(r, try files.write(r.a, r.snapshot_path, path, ".cs", "", marker, facade_source.?)) else null;
    try out.writeByte('{');
    if (written) |path| {
        try out.writeAll("\"path\":");
        try host.writeString(out, path);
    } else {
        try out.writeAll("\"source\":");
        try host.writeString(out, artifact.source);
    }
    if (facade_written) |path| {
        try out.writeAll(",\"facadePath\":");
        try host.writeString(out, path);
    }
    try out.writeAll(",\"symbols\":");
    try std.json.Stringify.value(artifact.symbols, .{}, out);
    try out.writeByte('}');
}
