//! `emitZigLibrary`: the Zig backend's library mode for the functions `<snapshot>.backends.json` lists
//! under "exports" (docs/decisions/zig-backend-memory-ownership.md, first milestone). The source goes
//! through the viewer writer's confinement; the caller builds it with `zig build-lib -dynamic`.
//! An optional "header" names a C header written the same way, from the same emitter walk.
const std = @import("std");
const q = @import("query.zig");
const recipe = @import("recipe.zig");
const emitter = @import("zig_emitter");
const model = @import("model_reader");
const host = @import("root");
const files = @import("view_file.zig");
const run_pure = @import("run_pure.zig");
const mapping = @import("zig_mapping.zig");
const marker = "// Generated by the Nyrwvy Zig backend.";

/// The display names listed under "exports" in the backends sidecar (tool configuration, outside
/// the fingerprint).
fn exportNames(r: *q.Request) ![]const []const u8 {
    const path = try std.mem.concat(r.a, u8, &.{ r.snapshot_path, ".backends.json" });
    const text = host.readText(r.a, path) catch |e| switch (e) {
        error.FileNotFound, error.NotDir => return r.fail("No functions are exported. Add \"exports\": [\"<function name>\"] to {s}.", .{path}),
        else => {
            r.rejection = .{ .code = "IoFailure", .message = @errorName(e) };
            return error.Rejected;
        },
    };
    const parsed = std.json.parseFromSliceLeaky(std.json.Value, r.a, text, .{ .duplicate_field_behavior = .use_last }) catch |e|
        return r.fail("{s} is not valid JSON: {s}", .{ path, @errorName(e) });
    const list = if (parsed == .object) parsed.object.get("exports") else null;
    if (list == null or list.? != .array or list.?.array.items.len == 0) return r.fail("No functions are exported. Add \"exports\": [\"<function name>\"] to {s}.", .{path});
    const names = try r.a.alloc([]const u8, list.?.array.items.len);
    for (list.?.array.items, names, 0..) |item, *name, i| {
        if (item != .string) return r.fail("{s}: \"exports\" must list function names.", .{path});
        name.* = try q.readable(r, item.string);
        for (names[0..i]) |prior| if (std.mem.eql(u8, prior, name.*)) return r.fail("{s} exports '{s}' twice.", .{ path, name.* });
    }
    return names;
}

/// The optional "zigTables" of the same sidecar: `<graph>.zig.json` files, relative to the snapshot.
fn tablePaths(r: *q.Request) ![]const []const u8 {
    const path = try std.mem.concat(r.a, u8, &.{ r.snapshot_path, ".backends.json" });
    const parsed = try std.json.parseFromSliceLeaky(std.json.Value, r.a, try host.readText(r.a, path), .{ .duplicate_field_behavior = .use_last });
    const list = parsed.object.get("zigTables") orelse return &.{};
    if (list != .array) return r.fail("{s}: \"zigTables\" must list table files.", .{path});
    const paths = try r.a.alloc([]const u8, list.array.items.len);
    for (list.array.items, paths) |item, *table| {
        if (item != .string) return r.fail("{s}: \"zigTables\" must list table files.", .{path});
        table.* = item.string;
    }
    return paths;
}

fn unsupported(r: *q.Request, problems: []const []const u8) anyerror {
    r.rejection = .{ .code = "RunBackendUnsupported", .message = try std.fmt.allocPrint(r.a, "The Zig library mode does not yet support: {s}.", .{try std.mem.join(r.a, ", ", problems[0..@min(problems.len, 8)])}) };
    return error.Rejected;
}

pub fn run(r: *q.Request, out: *std.Io.Writer) !void {
    var d: recipe.Decoder = .{ .r = r, .duplicates = try recipe.duplicatePaths(r.a, r.line) };
    const request: std.json.Value = .{ .object = r.root };
    try d.ensureFields("", request, "emitZigLibrary request", &.{ "id", "op", "output", "header" }, &.{ "id", "op" });
    const output = if (r.root.contains("output")) try d.requiredString(request, "output") else null;
    const header = if (r.root.contains("header")) try d.requiredString(request, "header") else null;
    try r.ensureUsable();
    if (try host.verifyPersisted(r.a)) |rejection| {
        r.rejection = rejection;
        return error.Rejected;
    }
    const names = try exportNames(r);
    const visible = try q.typedVisible(r, "function");
    const exports = try r.a.alloc(emitter.Export, names.len);
    // The validator cannot see a C caller, so whether an export may wait is reported for the host to honour.
    const wait_paths = try r.a.alloc(?model.Str, names.len);
    const root = model.typedRoot(r.a, r.interner.?, r.generation.?);
    for (names, exports, wait_paths) |name, *item, *wait_path| {
        const function = try q.typedExactOne(r, "function", name, visible);
        const symbol = try std.mem.concat(r.a, u8, &.{ "ny_", name });
        wait_path.* = model.typedFocusOf(r.a, root, function).wait_path;
        item.* = .{ .id = q.idOf(function), .symbol = symbol, .may_wait = wait_path.* != null };
    }
    const bound = try mapping.bindings(r, try tablePaths(r), output);
    var emitted = try emitter.library(r.a, try run_pure.lowered(r, null), exports, bound);
    // shortcut: a whole program the emitter cannot translate falls back to one export's reach only;
    // lower each export's reach and merge them when a library needs several.
    if (emitted == .unsupported and exports.len == 1) emitted = try emitter.library(r.a, try run_pure.lowered(r, exports[0].id), exports, bound);
    const source = switch (emitted) {
        .source => |source| source,
        .unsupported => |problems| return unsupported(r, problems),
    };
    try out.writeByte('{');
    if (output) |path| {
        const written = switch (try files.write(r.a, r.snapshot_path, path, ".zig", "", marker, source)) {
            .written => |written| written,
            .refused => |message| {
                r.rejection = .{ .code = "EmitWriteFailed", .message = message };
                return error.Rejected;
            },
            .internal => {
                r.rejection = .{ .code = "InternalError", .message = "Unexpected internal failure; this request was not applied and the session is unchanged." };
                return error.Rejected;
            },
        };
        try out.writeAll("\"path\":");
        try host.writeString(out, written);
    } else {
        try out.writeAll("\"source\":");
        try host.writeString(out, source);
    }
    if (header) |path| {
        // The emitter built the header in the same walk as the source; a missing one means the
        // emit took a path that produced no library, which the source above already ruled out.
        const text = emitter.takeLibraryHeader() orelse {
            r.rejection = .{ .code = "InternalError", .message = "Unexpected internal failure; this request was not applied and the session is unchanged." };
            return error.Rejected;
        };
        const written = switch (try files.write(r.a, r.snapshot_path, path, ".h", "", marker, text)) {
            .written => |written| written,
            .refused => |message| {
                r.rejection = .{ .code = "EmitWriteFailed", .message = message };
                return error.Rejected;
            },
            .internal => {
                r.rejection = .{ .code = "InternalError", .message = "Unexpected internal failure; this request was not applied and the session is unchanged." };
                return error.Rejected;
            },
        };
        try out.writeAll(",\"headerPath\":");
        try host.writeString(out, written);
    }
    try out.writeAll(",\"exports\":[");
    for (names, exports, wait_paths, 0..) |name, item, wait_path, i| {
        if (i > 0) try out.writeByte(',');
        try out.writeAll("{\"function\":");
        try host.writeString(out, name);
        try out.writeAll(",\"functionId\":");
        try host.writeString(out, item.id);
        try out.writeAll(",\"symbol\":");
        try host.writeString(out, item.symbol);
        if (wait_path) |path| {
            try out.writeAll(",\"mayWait\":true,\"waitPath\":");
            try model.writeString(out, path);
        }
        try out.writeByte('}');
    }
    try out.writeAll("]}");
}
